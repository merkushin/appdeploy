// Package export renders an app's setup as the configuration of other
// deployment tools, so that leaving appdeploy never means starting over.
//
// Only names of secrets are exported, never their values.
package export

import (
	"bytes"
	"encoding/json"
	"fmt"
	"net"
	"sort"
	"strings"

	"appdeploy/internal/config"
	"appdeploy/internal/docker"
	"appdeploy/internal/group"
)

// Spec is everything an exporter needs to know about an app.
type Spec struct {
	App         string
	Release     int
	Config      *config.App
	Domains     []string // from the app and its config
	SecretNames []string
	Servers     []group.Server // empty on a standalone server
}

// Formats lists the supported formats.
var Formats = []string{"kamal", "compose", "k8s", "fly"}

// Render returns the files of the format, by relative path.
func Render(format string, s Spec) (map[string]string, error) {
	if s.Config == nil {
		return nil, fmt.Errorf("the app has no release yet; deploy it first")
	}
	switch format {
	case "kamal":
		return kamal(s), nil
	case "compose":
		return compose(s), nil
	case "k8s":
		return k8s(s), nil
	case "fly":
		return fly(s), nil
	}
	return nil, fmt.Errorf("unknown format %q (use one of: %s)", format, strings.Join(Formats, ", "))
}

// q quotes a string for YAML or TOML (JSON strings are valid in both).
func q(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func sortedRoles(c *config.App) []string {
	names := make([]string, 0, len(c.Roles))
	for n := range c.Roles {
		names = append(names, n)
	}
	sort.Slice(names, func(i, j int) bool {
		if (names[i] == "web") != (names[j] == "web") {
			return names[i] == "web"
		}
		return names[i] < names[j]
	})
	return names
}

// webPort is the port the web role listens on.
func webPort(c *config.App) int {
	if r := c.Roles["web"]; r != nil && r.Port > 0 {
		return r.Port
	}
	return config.DefaultPort
}

// args splits a role's command the way appdeploy runs it.
func args(cmd string) []string {
	a, err := docker.SplitCommand(cmd)
	if err != nil {
		return []string{cmd}
	}
	return a
}

// hosts returns the addresses of the servers that run a role, or a placeholder.
func hosts(s Spec, r *config.Role) []string {
	var out []string
	for _, srv := range s.Servers {
		if srv.HasLabel(r.On...) {
			h, _, err := net.SplitHostPort(srv.Addr)
			if err != nil {
				h = srv.Addr
			}
			out = append(out, h)
		}
	}
	if len(out) == 0 {
		out = []string{"your.server.ip"}
	}
	return out
}

// image is where the exported config expects the release image to be: appdeploy
// keeps images on the servers, so it has to be pushed to a registry first.
func image(s Spec) string { return "your-registry.example.com/" + s.App + ":v" + fmt.Sprint(s.Release) }

// serviceEnv lists the variables appdeploy provides for services, which the
// target has to provide itself.
func serviceEnv(c *config.App) []string {
	var out []string
	if c.Services.Postgres {
		out = append(out, "DATABASE_URL")
	}
	if c.Services.Redis {
		out = append(out, "REDIS_URL")
	}
	return out
}

// allEnvNames are the names the app expects to find in its environment.
func allEnvNames(s Spec) []string {
	seen := map[string]bool{}
	var out []string
	for _, n := range append(append([]string{}, s.SecretNames...), serviceEnv(s.Config)...) {
		if !seen[n] {
			seen[n] = true
			out = append(out, n)
		}
	}
	sort.Strings(out)
	return out
}

func mem(r *config.Role) string {
	b := r.Memory.Bytes()
	switch {
	case b%(1<<30) == 0:
		return fmt.Sprintf("%dG", b>>30)
	default:
		return fmt.Sprintf("%dM", b>>20)
	}
}

func header(w *bytes.Buffer, tool string, s Spec) {
	fmt.Fprintf(w, "# Generated by appdeploy export from %s v%d for %s.\n", s.App, s.Release, tool)
	fmt.Fprintf(w, "# Secret values are not included; provide them yourself (see the list of names below or in the env file).\n")
}

// plainEnv returns the non-secret environment, sorted by name.
func plainEnv(c *config.App) [][2]string {
	keys := make([]string, 0, len(c.Env))
	for k := range c.Env {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	out := make([][2]string, len(keys))
	for i, k := range keys {
		out[i] = [2]string{k, c.Env[k]}
	}
	return out
}

// mount is one volume of a role: its name, where it is mounted, and whether read-only.
type mount struct {
	Name, Path string
	RO         bool
}

func mountsOf(r *config.Role) []mount {
	var out []mount
	for _, v := range r.Volumes {
		if n, p, ro, err := config.ParseVolume(v); err == nil {
			out = append(out, mount{n, p, ro})
		}
	}
	return out
}

// volumeNames lists the distinct volume names of the app.
func volumeNames(c *config.App) []string {
	seen := map[string]bool{}
	var out []string
	for _, role := range sortedRoles(c) {
		for _, m := range mountsOf(c.Roles[role]) {
			if !seen[m.Name] {
				seen[m.Name] = true
				out = append(out, m.Name)
			}
		}
	}
	return out
}
